-- Estrutura PostgreSQL usada pelo serviço analytics-python.
-- A aplicação também cria estas tabelas automaticamente via SQLAlchemy.

CREATE TABLE IF NOT EXISTS upload_lote (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    arquivo_nome VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL,
    total_linhas INTEGER NOT NULL,
    linhas_validas INTEGER NOT NULL,
    linhas_invalidas INTEGER NOT NULL,
    mensagem VARCHAR(500),
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS segmento (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS consultor (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS servico (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS cliente (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id INTEGER NOT NULL REFERENCES upload_lote(id) ON DELETE CASCADE,
    codigo_cti VARCHAR(30) NOT NULL,
    nome VARCHAR(150) NOT NULL,
    consultor VARCHAR(120) NOT NULL,
    consultor_id INTEGER NOT NULL REFERENCES consultor(id),
    segmento VARCHAR(100) NOT NULL,
    segmento_id INTEGER NOT NULL REFERENCES segmento(id),
    nivel VARCHAR(1) NOT NULL,
    faturamento_anual DOUBLE PRECISION NOT NULL,
    data_contratacao DATE NOT NULL,
    cidade VARCHAR(100),
    uf VARCHAR(2),
    CONSTRAINT uq_cliente_lote_codigo UNIQUE (lote_id, codigo_cti)
);

CREATE TABLE IF NOT EXISTS contrato (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id INTEGER NOT NULL REFERENCES cliente(id) ON DELETE CASCADE,
    servico VARCHAR(120) NOT NULL,
    servico_id INTEGER NOT NULL REFERENCES servico(id),
    data_contratacao DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS estatistica_lote (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id INTEGER NOT NULL UNIQUE REFERENCES upload_lote(id) ON DELETE CASCADE,
    resultado JSON NOT NULL
);
